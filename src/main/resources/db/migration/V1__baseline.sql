-- Baseline of the schema Hibernate (ddl-auto=update) and SchemaInitializer built in production.
--
-- Written to be idempotent: the production database already has most of this, and Flyway is set to
-- baseline it at version 0 (application-prod.properties), so this script also runs there and only
-- adds what is missing. On an empty database it creates everything. From V2 on, plain migrations.

CREATE TABLE IF NOT EXISTS tasks (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name             VARCHAR(255),
    description      TEXT,
    type             VARCHAR(255),
    frequency        VARCHAR(255),
    default_assignee VARCHAR(255),
    points           INTEGER NOT NULL,
    time_window      VARCHAR(255),
    deadline         VARCHAR(255),
    active           BOOLEAN NOT NULL,
    sort_order       INTEGER NOT NULL,
    one_off          BOOLEAN NOT NULL DEFAULT FALSE
);

CREATE TABLE IF NOT EXISTS assignments (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    task_id         BIGINT NOT NULL REFERENCES tasks (id),
    assigned_to     VARCHAR(255),
    period_date     DATE,
    period_week     DATE,
    completed_at    TIMESTAMP(6),
    bonus_earned    BOOLEAN NOT NULL,
    penalty_applied BOOLEAN NOT NULL,
    missed_deadline BOOLEAN NOT NULL,
    deleted         BOOLEAN NOT NULL DEFAULT FALSE,
    UNIQUE (task_id, period_date, period_week)
);

-- child1name etc. have no underscore: Spring's naming strategy adds none after a digit.
CREATE TABLE IF NOT EXISTS family_config (
    id          BIGINT PRIMARY KEY,
    child1name  VARCHAR(255),
    child2name  VARCHAR(255),
    child1phone VARCHAR(255),
    child2phone VARCHAR(255)
);

CREATE TABLE IF NOT EXISTS point_ledger (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    assignee   VARCHAR(255),
    week_start DATE,
    delta      INTEGER NOT NULL,
    reason     VARCHAR(255)
);

CREATE TABLE IF NOT EXISTS rewards (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name        VARCHAR(255),
    points_cost INTEGER NOT NULL,
    emoji       VARCHAR(255),
    active      BOOLEAN NOT NULL
);

CREATE TABLE IF NOT EXISTS push_subscriptions (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    endpoint   VARCHAR(1000) NOT NULL UNIQUE,
    p256dh     VARCHAR(255) NOT NULL,
    auth       VARCHAR(255) NOT NULL,
    assignee   VARCHAR(255),
    created_at TIMESTAMP(6)
);

CREATE TABLE IF NOT EXISTS reminder_log (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    reminder_date DATE,
    slot          VARCHAR(255),
    sent_at       TIMESTAMP(6),
    UNIQUE (reminder_date, slot)
);

-- ── Columns added to existing tables after the first deploy (were in SchemaInitializer) ──────────

-- Production also has columns no entity maps (tasks.deadline_date, family_config.child1_phone and
-- child2_phone, which SchemaInitializer created under the wrong name); they are left out here.
ALTER TABLE tasks ALTER COLUMN description TYPE TEXT;

ALTER TABLE tasks ADD COLUMN IF NOT EXISTS one_off BOOLEAN;
UPDATE tasks SET one_off = FALSE WHERE one_off IS NULL;
ALTER TABLE tasks ALTER COLUMN one_off SET DEFAULT FALSE;
ALTER TABLE tasks ALTER COLUMN one_off SET NOT NULL;

ALTER TABLE family_config ADD COLUMN IF NOT EXISTS child1phone VARCHAR(255);
ALTER TABLE family_config ADD COLUMN IF NOT EXISTS child2phone VARCHAR(255);

ALTER TABLE assignments ADD COLUMN IF NOT EXISTS deleted BOOLEAN;
UPDATE assignments SET deleted = FALSE WHERE deleted IS NULL;
ALTER TABLE assignments ALTER COLUMN deleted SET DEFAULT FALSE;
ALTER TABLE assignments ALTER COLUMN deleted SET NOT NULL;

-- ── One assignment per task and day / week ─────────────────────────────────────────────────────
-- SchemaInitializer skipped these on error; here too, so existing duplicates can't block the boot.
DO $$
BEGIN
    CREATE UNIQUE INDEX IF NOT EXISTS uq_assignment_daily
        ON assignments (task_id, period_date) WHERE period_date IS NOT NULL;
EXCEPTION WHEN unique_violation THEN
    RAISE WARNING 'uq_assignment_daily not created: duplicate daily assignments exist';
END $$;

DO $$
BEGIN
    CREATE UNIQUE INDEX IF NOT EXISTS uq_assignment_weekly
        ON assignments (task_id, period_week) WHERE period_week IS NOT NULL;
EXCEPTION WHEN unique_violation THEN
    RAISE WARNING 'uq_assignment_weekly not created: duplicate weekly assignments exist';
END $$;
