/**
 * Production runs on PostgreSQL with the schema from Flyway (db/migration) and ddl-auto=none; every
 * other test uses H2 with a schema Hibernate creates. This one boots the app on a real PostgreSQL
 * (embedded binary, no Docker) with the migrations and ddl-auto=validate, so a migration that does not
 * match the entities, or SQL only PostgreSQL rejects, fails here instead of on Render.
 */
@SpringBootTest(
    properties = [
        "spring.flyway.enabled=true",
        "spring.flyway.baseline-on-migrate=true",
        "spring.flyway.baseline-version=0",
        "spring.jpa.hibernate.ddl-auto=validate",
        "spring.jpa.database-platform=org.hibernate.dialect.PostgreSQLDialect",
    ],
)
@ActiveProfiles("test")
class PostgresMigrationTest {

    companion object {
        private val postgres: EmbeddedPostgres = EmbeddedPostgres.start()

        @JvmStatic
        @DynamicPropertySource
        fun datasource(registry: DynamicPropertyRegistry) {
            registry.add("spring.datasource.url") { postgres.getJdbcUrl("postgres", "postgres") }
            registry.add("spring.datasource.username") { "postgres" }
            registry.add("spring.datasource.password") { "postgres" }
            registry.add("spring.datasource.driver-class-name") { "org.postgresql.Driver" }
        }

        @JvmStatic
        @AfterAll
        fun stop() = postgres.close()
    }

    @Autowired lateinit var jdbc: JdbcTemplate
    @Autowired lateinit var tasks: TaskRepository
    @Autowired lateinit var assignments: AssignmentRepository
    @Autowired lateinit var routine: DailyRoutineService
    @Autowired lateinit var pushSubscriptions: PushSubscriptionRepository
    @Autowired lateinit var reminderLog: ReminderLogRepository

    @Test
    fun `the app runs on the migrated schema`() {
        assertTrue(tasks.count() > 0, "DataSeeder should have seeded the tasks")

        val day = LocalDate.of(2026, 10, 14)
        routine.run(day)
        routine.run(day)
        assertTrue(assignments.findByPeriodDate(day).isNotEmpty())
        assertEquals(
            0,
            jdbc.queryForObject(
                "SELECT count(*) FROM (SELECT task_id FROM assignments WHERE period_date = ? GROUP BY task_id HAVING count(*) > 1) d",
                Int::class.java,
                day,
            ),
        )

        pushSubscriptions.save(PushSubscription(endpoint = "https://push.example/1", p256dh = "k", auth = "a", assignee = Assignee.CHILD1))
        reminderLog.save(ReminderLog(date = day, slot = "NOON"))
        assertTrue(reminderLog.existsByDateAndSlot(day, "NOON"))
    }

    @Test
    fun `the production database that predates Flyway is baselined and completed by V1`() {
        EmbeddedPostgres.start().use { legacy ->
            val db = legacy.postgresDatabase
            // Roughly what ddl-auto=update + SchemaInitializer left behind, before one_off, deleted,
            // the phones and the push tables existed.
            JdbcTemplate(db).execute(
                """
                CREATE TABLE tasks (id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, name VARCHAR(255),
                    description VARCHAR(255), type VARCHAR(255), frequency VARCHAR(255), default_assignee VARCHAR(255),
                    points INTEGER NOT NULL, time_window VARCHAR(255), deadline VARCHAR(255), active BOOLEAN NOT NULL,
                    sort_order INTEGER NOT NULL, deadline_date TIMESTAMP);
                CREATE TABLE assignments (id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                    task_id BIGINT NOT NULL REFERENCES tasks (id), assigned_to VARCHAR(255), period_date DATE,
                    period_week DATE, completed_at TIMESTAMP(6), bonus_earned BOOLEAN NOT NULL,
                    penalty_applied BOOLEAN NOT NULL, missed_deadline BOOLEAN NOT NULL,
                    UNIQUE (task_id, period_date, period_week));
                CREATE TABLE family_config (id BIGINT PRIMARY KEY, child1name VARCHAR(255), child2name VARCHAR(255),
                    child1_phone VARCHAR(64) NOT NULL DEFAULT '', child2_phone VARCHAR(64) NOT NULL DEFAULT '');
                CREATE TABLE point_ledger (id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, assignee VARCHAR(255),
                    week_start DATE, delta INTEGER NOT NULL, reason VARCHAR(255));
                CREATE TABLE rewards (id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, name VARCHAR(255),
                    points_cost INTEGER NOT NULL, emoji VARCHAR(255), active BOOLEAN NOT NULL);
                INSERT INTO tasks (name, points, active, sort_order) VALUES ('Lixo', 0, true, 1);
                INSERT INTO assignments (task_id, period_date, bonus_earned, penalty_applied, missed_deadline)
                    VALUES (1, DATE '2026-10-13', false, false, false);
                """.trimIndent(),
            )

            Flyway.configure().dataSource(db).baselineOnMigrate(true).baselineVersion("0").load().migrate()

            val jdbc = JdbcTemplate(db)
            assertEquals(
                listOf("0", "1"),
                jdbc.queryForList("SELECT version FROM flyway_schema_history ORDER BY installed_rank", String::class.java),
            )
            assertEquals(false, jdbc.queryForObject("SELECT one_off FROM tasks", Boolean::class.java))
            assertEquals(false, jdbc.queryForObject("SELECT deleted FROM assignments", Boolean::class.java))
            assertEquals(
                setOf("push_subscriptions", "reminder_log", "child1phone", "child2phone", "uq_assignment_daily", "uq_assignment_weekly"),
                jdbc.queryForList(
                    """
                    SELECT table_name FROM information_schema.tables WHERE table_name IN ('push_subscriptions', 'reminder_log')
                    UNION SELECT column_name FROM information_schema.columns WHERE table_name = 'family_config' AND column_name LIKE 'child_phone'
                    UNION SELECT indexname FROM pg_indexes WHERE indexname LIKE 'uq_assignment_%'
                    """,
                    String::class.java,
                ).toSet(),
            )
        }
    }
}
